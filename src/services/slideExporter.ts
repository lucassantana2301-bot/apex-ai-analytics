import type { ExecutiveSummary, Dataset } from '../types/dataset';

export function exportPresentationSlideDeck(dataset: Dataset, summary: ExecutiveSummary): void {
  const slidesHtml = `
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <title>Executive Slide Deck - ${dataset.name}</title>
      <style>
        * { box-sizing: border-box; margin: 0; padding: 0; }
        body { font-family: 'Segoe UI', system-ui, sans-serif; background: #031930; color: #ffffff; overflow-x: hidden; }
        .slide {
          width: 100vw;
          height: 100vh;
          padding: 60px;
          display: flex;
          flex-direction: column;
          justify-content: center;
          border-bottom: 4px solid #06b6d4;
          page-break-after: always;
        }
        h1 { font-size: 3rem; color: #38bdf8; margin-bottom: 20px; text-transform: uppercase; }
        h2 { font-size: 2.2rem; color: #ffffff; margin-bottom: 24px; border-bottom: 2px solid #0284c7; padding-bottom: 12px; }
        p { font-size: 1.3rem; color: #cbd5e1; line-height: 1.6; margin-bottom: 20px; }
        .kpi-grid { display: grid; grid-template-columns: repeat(2, 1fr); gap: 24px; margin-top: 20px; }
        .kpi-card { background: rgba(255,255,255,0.06); padding: 30px; borderRadius: 16px; border: 1px solid rgba(6,182,212,0.3); }
        .kpi-value { font-size: 2.8rem; font-weight: bold; color: #38bdf8; }
        .kpi-label { font-size: 1.1rem; color: #94a3b8; text-transform: uppercase; }
        ul { font-size: 1.2rem; line-height: 2; color: #f8fafc; padding-left: 30px; }
        .badge { background: #0284c7; padding: 8px 16px; border-radius: 20px; font-weight: bold; }
      </style>
    </head>
    <body>
      <!-- Slide 1: Cover Title -->
      <div class="slide">
        <span class="badge">AI EXECUTIVE TELEMETRY BRIEFING</span>
        <h1 style="margin-top: 20px;">${dataset.name}</h1>
        <p>Executive Analytics, Automated Anomaly Detection & Strategic Insights</p>
        <p style="font-size: 1rem; color: #64748b; margin-top: 40px;">Generated by AI Data Insights Engine • ${new Date().toLocaleDateString()}</p>
      </div>

      <!-- Slide 2: Overview & Health -->
      <div class="slide">
        <h2>Dataset Overview & Telemetry Integrity</h2>
        <p>${summary.overview}</p>
        <div style="margin-top: 30px;">
          <span class="badge" style="font-size: 1.5rem; background: #06b6d4;">Quality Score: ${summary.qualityScore} / 100</span>
        </div>
      </div>

      <!-- Slide 3: Key Performance Metrics -->
      <div class="slide">
        <h2>Key Numerical Indicators</h2>
        <div class="kpi-grid">
          ${summary.keyMetrics
            .map(
              (m) => `
            <div class="kpi-card">
              <div class="kpi-label">${m.label}</div>
              <div class="kpi-value">${m.value}</div>
              <div style="font-size: 0.95rem; color: #94a3b8; margin-top: 8px;">${m.subtitle || ''}</div>
            </div>
          `
            )
            .join('')}
        </div>
      </div>

      <!-- Slide 4: Strategic Directives -->
      <div class="slide">
        <h2>Strategic Directives & Recommendations</h2>
        <ul>
          ${summary.recommendations.map((r) => `<li>${r}</li>`).join('')}
        </ul>
      </div>
    </body>
    </html>
  `;

  const blob = new Blob([slidesHtml], { type: 'text/html;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${dataset.name.toLowerCase().replace(/\s+/g, '_')}_slide_deck.html`;
  link.click();
  URL.revokeObjectURL(url);
}
